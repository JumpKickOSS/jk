package cc.jumpkick.format;

import static org.assertj.core.api.Assertions.assertThat;

import com.diffplug.spotless.Formatter;
import com.diffplug.spotless.LineEnding;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * A generated source is left as it is by {@code jk format}, recognised by its header's marker and
 * never by how long the header's lines are (a 150-column {@code // GENERATED ... DO
 * NOT EDIT} line was rewrapped, its 105-column twin came out unchanged only because it fit).
 */
class GeneratedSourceTest {

    private static final String LONG_MARKER = "// GENERATED by sqlgen dev from db/queries/users.sql and"
            + " db/queries/_generated/users.sql. DO NOT EDIT: edit the .sql files and run 'sqlgen gen'.";

    private static final String SHORT_MARKER =
            "// GENERATED by sqlgen dev from db/queries/users.sql. DO NOT EDIT: run 'sqlgen gen'.";

    @Test
    void the_marker_counts_whatever_the_length_of_its_line() {
        assertThat(LONG_MARKER.length()).isGreaterThan(140);
        assertThat(GeneratedSource.isGenerated(LONG_MARKER + "\npackage a;\nclass A {}\n"))
                .isTrue();
        assertThat(GeneratedSource.isGenerated(SHORT_MARKER + "\npackage a;\nclass A {}\n"))
                .isTrue();
        assertThat(GeneratedSource.isGenerated(
                        "// GENERATED by sqlgen 0.1.0 from tags.sql.\n// DO NOT EDIT: run 'sqlgen gen'.\npackage a;\n"))
                .isTrue();
    }

    @Test
    void the_markers_generators_write_are_recognised() {
        assertThat(GeneratedSource.isGenerated("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage a;"))
                .isTrue();
        assertThat(GeneratedSource.isGenerated("/*\n * @generated by Thrift\n */\npackage a;"))
                .isTrue();
        assertThat(GeneratedSource.isGenerated("/**\n * Auto-generated from schema.graphql\n */\npackage a;"))
                .isTrue();
        assertThat(GeneratedSource.isGenerated(
                        "// SPDX-License-Identifier: Apache-2.0\n\n// This file was generated by sqlc.\npackage a"))
                .isTrue();
        assertThat(GeneratedSource.isGenerated("﻿// generated by kapt\npackage a"))
                .isTrue();
    }

    @Test
    void a_hand_written_file_is_not_generated() {
        assertThat(GeneratedSource.isGenerated("// SPDX-License-Identifier: Apache-2.0\npackage a;\nclass A {}\n"))
                .isFalse();
        assertThat(GeneratedSource.isGenerated("// Reads generated files.\npackage a;\nclass A {}\n"))
                .as("a header that mentions generation without a banner's opening")
                .isFalse();
        assertThat(GeneratedSource.isGenerated(
                        "package a;\n// DO NOT EDIT this constant without the migration.\nclass A {}\n"))
                .as("a marker below the first code is not a header")
                .isFalse();
        assertThat(GeneratedSource.isGenerated("package a;\nclass A { String s = \"@generated\"; }\n"))
                .isFalse();
    }

    @Test
    void the_formatter_leaves_a_generated_file_with_a_long_marker_line_unchanged(@TempDir Path tmp) throws Exception {
        // Unformatted Groovy: the semicolon step would strip it, as Palantir rewraps a long comment.
        Path file = tmp.resolve("Gen.groovy");
        byte[] source = (LONG_MARKER + "\nclass Gen {\n    def x = 1;\n}\n").getBytes(StandardCharsets.UTF_8);
        Files.write(file, source);
        var ref = new CodeFormatter.FileRef(CodeFormatter.Kind.GROOVY, file.toFile());
        var spec = new CodeFormatter.Spec();

        try (Formatter fmt = groovy()) {
            var result = CodeFormatter.commit(CodeFormatter.formatOne(ref, fmt, spec, null, null), null);
            assertThat(result.status()).isEqualTo("skipped");
        }
        assertThat(Files.readAllBytes(file)).isEqualTo(source);

        Path hand = tmp.resolve("Hand.groovy");
        Files.writeString(hand, "class Hand {\n    def x = 1;\n}\n");
        try (Formatter fmt = groovy()) {
            var ref2 = new CodeFormatter.FileRef(CodeFormatter.Kind.GROOVY, hand.toFile());
            assertThat(CodeFormatter.formatOne(ref2, fmt, spec, null, null).status())
                    .as("a hand-written file is still formatted")
                    .isEqualTo("changed");
        }
    }

    private static Formatter groovy() {
        return Formatter.builder()
                .lineEndingsPolicy(LineEnding.UNIX.createPolicy())
                .encoding(StandardCharsets.UTF_8)
                .steps(CodeFormatter.groovySteps())
                .build();
    }
}
