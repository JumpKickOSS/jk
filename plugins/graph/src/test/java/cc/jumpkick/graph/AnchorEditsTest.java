package cc.jumpkick.graph;

import static org.assertj.core.api.Assertions.assertThat;

import cc.jumpkick.layout.AnchorWatch;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * A hand edit that renames one side of an anchor, on petclinic's own shapes: the column in one
 * dialect's schema while the other dialect and the entity still say {@code telephone}; the config
 * key in {@code application.properties} while compose still sets {@code PETCLINIC_VISITS_MAXPERDAY}.
 * The record names each place still under the old name, graded; an edit that changes no name, or a
 * use dropped, names nothing; a place fixed or an edit undone leaves the record.
 */
class AnchorEditsTest {

    static final String H2 = "src/main/resources/db/h2/schema.sql";
    static final String MYSQL = "src/main/resources/db/mysql/schema.sql";
    static final String OWNER = "src/main/java/org/springframework/samples/petclinic/owner/Owner.java";
    static final String PROPERTIES = "src/main/resources/application.properties";
    static final String VISIT_LIMITS = "src/main/java/org/springframework/samples/petclinic/system/VisitLimits.java";

    static Map<String, String> petclinic() {
        return RenameFixture.files(
                "src/main/java/jakarta/persistence/Entity.java",
                "package jakarta.persistence;\n\npublic @interface Entity {}\n",
                "src/main/java/jakarta/persistence/Column.java",
                "package jakarta.persistence;\n\npublic @interface Column {\n    String name() default \"\";\n}\n",
                "src/main/java/jakarta/persistence/Table.java",
                "package jakarta.persistence;\n\npublic @interface Table {\n    String name() default \"\";\n}\n",
                "src/main/java/org/springframework/boot/context/properties/ConfigurationProperties.java",
                """
                package org.springframework.boot.context.properties;

                public @interface ConfigurationProperties {
                    String value() default "";

                    String prefix() default "";
                }
                """,
                OWNER,
                """
                package org.springframework.samples.petclinic.owner;

                import jakarta.persistence.Column;
                import jakarta.persistence.Entity;
                import jakarta.persistence.Table;

                @Entity
                @Table(name = "owners")
                public class Owner {

                    @Column(name = "address")
                    private String address;

                    @Column(name = "telephone")
                    private String telephone;

                    public String getTelephone() {
                        return this.telephone;
                    }

                    public String summary() {
                        return this.address + " " + this.telephone;
                    }
                }
                """,
                VISIT_LIMITS,
                """
                package org.springframework.samples.petclinic.system;

                import org.springframework.boot.context.properties.ConfigurationProperties;

                @ConfigurationProperties(prefix = "petclinic.visits")
                public class VisitLimits {

                    private int maxPerDay = 10;

                    public int getMaxPerDay() {
                        return this.maxPerDay;
                    }

                    public void setMaxPerDay(int maxPerDay) {
                        this.maxPerDay = maxPerDay;
                    }
                }
                """,
                H2,
                """
                CREATE TABLE owners (
                  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  address    VARCHAR(255),
                  telephone  VARCHAR(20)
                );
                """,
                MYSQL,
                """
                CREATE TABLE IF NOT EXISTS owners (
                  id INT(4) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
                  address VARCHAR(255),
                  telephone VARCHAR(20)
                ) engine=InnoDB;
                """,
                PROPERTIES,
                "spring.application.name=petclinic\npetclinic.visits.max-per-day=20\n",
                "docker-compose.yml",
                """
                services:
                  app:
                    image: spring-petclinic:latest
                    environment:
                      - SPRING_PROFILES_ACTIVE=h2
                      - PETCLINIC_VISITS_MAXPERDAY=40
                """,
                "README.md",
                """
                # Spring PetClinic

                Each owner has an address and a telephone number, stored in the owners table.
                """);
    }

    /** Refreshes the graph as a build or a graph question does, and the record it leaves. */
    static List<String> refresh(RenameFixture ws) throws IOException {
        GraphService.Request r = new GraphService.Request(
                "build", List.of(), "bfs", 3, 2000, List.of(), false, 8, null, false, false, null, List.of(), null,
                Map.of());
        GraphService.run(ws.workspace(), r, GraphBuild.Progress.NONE);
        return rows(ws);
    }

    static List<String> rows(RenameFixture ws) {
        return AnchorEdits.read(
                        ws.root.resolve("target/graph").resolve(AnchorEdits.DIR).resolve(AnchorEdits.FILE))
                .stream()
                .map(r -> (r.must() ? "must " : "may ") + r.place() + " " + r.kind() + " " + r.old() + ">" + r.now()
                        + (r.written().isEmpty() ? "" : " as " + r.written()) + " " + r.rel() + ":" + r.line()
                        + " after " + r.edited())
                .toList();
    }

    static void edit(RenameFixture ws, String rel, String from, String to) throws IOException {
        Path f = ws.root.resolve(rel);
        String text = Files.readString(f);
        assertThat(text).contains(from);
        Files.writeString(f, text.replace(from, to));
    }

    @Test
    void aColumnRenamedInOneSchemaNamesTheOtherSchemaAndTheEntityAndCountsTheProse(@TempDir Path dir)
            throws IOException {
        RenameFixture ws = new RenameFixture(dir, petclinic());
        assertThat(refresh(ws)).as("the first graph has no before").isEmpty();

        edit(ws, H2, "  telephone  VARCHAR(20)", "  phone      VARCHAR(20)");

        assertThat(refresh(ws))
                .containsExactlyInAnyOrder(
                        "must sql column owners.telephone>owners.phone " + MYSQL + ":4 after " + H2,
                        "must java column owners.telephone>owners.phone " + OWNER + ":15 after " + H2,
                        "may md column owners.telephone>owners.phone README.md:3 after " + H2);

        // A build that follows still names them: the record is kept until the places change.
        assertThat(refresh(ws)).hasSize(3);

        edit(ws, MYSQL, "  telephone VARCHAR(20)", "  phone VARCHAR(20)");
        assertThat(refresh(ws))
                .as("the other schema, fixed, leaves; the entity has not changed, and the later edit owns it")
                .containsExactlyInAnyOrder(
                        "must java column owners.telephone>owners.phone " + OWNER + ":15 after " + MYSQL,
                        "may md column owners.telephone>owners.phone README.md:3 after " + MYSQL);
    }

    /**
     * The entity remapped to the new column in the same edit is not a place left behind, though its
     * property keeps the word {@code telephone}: the new graph says what it maps.
     */
    @Test
    void anEntityRemappedToTheNewColumnIsNotListedThoughItsPropertyKeepsTheOldWord(@TempDir Path dir)
            throws IOException {
        RenameFixture ws = new RenameFixture(dir, petclinic());
        refresh(ws);

        edit(ws, H2, "  telephone  VARCHAR(20)", "  phone      VARCHAR(20)");
        edit(ws, OWNER, "@Column(name = \"telephone\")", "@Column(name = \"phone\")");
        assertThat(ws.compile()).isNull();

        assertThat(refresh(ws))
                .containsExactlyInAnyOrder(
                        "must sql column owners.telephone>owners.phone " + MYSQL + ":4 after " + OWNER,
                        "may md column owners.telephone>owners.phone README.md:3 after " + OWNER);
    }

    @Test
    void anEditUndoneLeavesNothing(@TempDir Path dir) throws IOException {
        RenameFixture ws = new RenameFixture(dir, petclinic());
        refresh(ws);
        edit(ws, H2, "  telephone  VARCHAR(20)", "  phone      VARCHAR(20)");
        assertThat(refresh(ws)).isNotEmpty();

        edit(ws, H2, "  phone      VARCHAR(20)", "  telephone  VARCHAR(20)");

        assertThat(refresh(ws)).isEmpty();
        assertThat(ws.exists("target/graph/anchors/stale")).isFalse();
    }

    @Test
    void aConfigKeyRenamedByHandNamesTheVariableThatSetsItAndTheClassThatBindsIt(@TempDir Path dir) throws IOException {
        RenameFixture ws = new RenameFixture(dir, petclinic());
        refresh(ws);

        edit(ws, PROPERTIES, "petclinic.visits.max-per-day=20", "petclinic.visits.daily-limit=20");

        List<String> rows = refresh(ws);
        assertThat(rows)
                .contains("must yml config petclinic.visits.max-per-day>petclinic.visits.daily-limit"
                        + " as PETCLINIC_VISITS_MAXPERDAY docker-compose.yml:6 after " + PROPERTIES)
                .anySatisfy(r -> assertThat(r)
                        .startsWith("must java config petclinic.visits.max-per-day>petclinic.visits.daily-limit")
                        .contains("system/VisitLimits.java:"));

        edit(ws, "docker-compose.yml", "PETCLINIC_VISITS_MAXPERDAY", "PETCLINIC_VISITS_DAILYLIMIT");
        assertThat(refresh(ws)).noneMatch(r -> r.contains("docker-compose.yml"));
    }

    @Test
    void anEditThatChangesNoNameAndAUseDroppedNameNothing(@TempDir Path dir) throws IOException {
        RenameFixture ws = new RenameFixture(dir, petclinic());
        refresh(ws);

        edit(
                ws,
                OWNER,
                "return this.address + \" \" + this.telephone;",
                "return this.address + \", \" + this.telephone;");
        assertThat(ws.compile()).isNull();
        edit(ws, H2, "VARCHAR(255)", "VARCHAR(300)");
        assertThat(refresh(ws)).as("a method body and a column's type").isEmpty();

        edit(ws, "docker-compose.yml", "      - PETCLINIC_VISITS_MAXPERDAY=40\n", "");
        assertThat(refresh(ws))
                .as("a variable no longer set: the key it set is still defined")
                .isEmpty();
        assertThat(ws.exists("target/graph/anchors/stale")).isFalse();
    }

    /**
     * Each refresh lists the files a build's verdict checks before it waits for the next one: those
     * that define or use an anchor, and those the record names. An edit to any of them shows; an
     * edit elsewhere does not, so that verdict waits for nothing.
     */
    @Test
    void theRefreshListsTheAnchoredFilesAndTheRecordsSoAnEditElsewhereNeedsNoWait(@TempDir Path dir)
            throws IOException {
        RenameFixture ws = new RenameFixture(dir, petclinic());
        refresh(ws);
        Path graph = ws.root.resolve("target/graph");
        assertThat(watched(graph))
                .contains(H2, MYSQL, OWNER, PROPERTIES, "docker-compose.yml")
                .anyMatch(r -> r.endsWith("system/VisitLimits.java"))
                .doesNotContain("README.md");
        assertThat(AnchorWatch.unchanged(ws.root, graph)).isTrue();

        edit(ws, "README.md", "Each owner has", "Every owner has");
        assertThat(AnchorWatch.unchanged(ws.root, graph))
                .as("prose no record names")
                .isTrue();
        edit(ws, H2, "VARCHAR(255)", "VARCHAR(300)");
        assertThat(AnchorWatch.unchanged(ws.root, graph)).as("a schema").isFalse();

        refresh(ws);
        assertThat(AnchorWatch.unchanged(ws.root, graph)).isTrue();
        edit(ws, H2, "  telephone  VARCHAR(20)", "  phone      VARCHAR(20)");
        refresh(ws);
        assertThat(watched(graph)).as("the record's prose place").contains("README.md");
    }

    /**
     * The list names each file's anchors, so two edits that meet only at an anchor can be told
     * apart from two that do not: the properties file defines the key the bound class uses, compose
     * sets it through the variable that binds to it, and a schema defines the column the entity maps.
     */
    @Test
    void theListNamesTheAnchorsEachFileDefinesOrUses(@TempDir Path dir) throws IOException {
        RenameFixture ws = new RenameFixture(dir, petclinic());
        refresh(ws);
        Map<String, Map<String, Boolean>> anchors = AnchorWatch.anchors(ws.root.resolve("target/graph"));
        String key = "config:petclinic.visits.maxperday";
        assertThat(anchors.get(PROPERTIES)).containsEntry(key, true);
        assertThat(anchors.get(VISIT_LIMITS)).containsEntry(key, false);
        assertThat(anchors.get("docker-compose.yml"))
                .containsEntry("env:PETCLINIC_VISITS_MAXPERDAY", true)
                .containsEntry(key, true);
        assertThat(anchors.get(H2)).containsEntry("column:owners.telephone", true);
        assertThat(anchors.get(OWNER))
                .containsEntry("column:owners.telephone", false)
                .doesNotContainKey(key);
        assertThat(anchors).doesNotContainKey("README.md");
    }

    private static List<String> watched(Path graph) throws IOException {
        return Files.readAllLines(AnchorWatch.file(graph)).stream()
                .skip(1)
                .map(l -> l.split("\t", -1)[2])
                .toList();
    }
}
