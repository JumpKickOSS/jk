package cc.jumpkick.engine.savings;

import cc.jumpkick.engine.sessions.ActionRecord;
import cc.jumpkick.jsonl.MiniJson;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;
import java.util.function.Function;
import org.jspecify.annotations.Nullable;

/**
 * The tokens one graph call saves an agent, per agent, in the question tasks and in the rename tasks
 * of the bench. {@code rates.json} beside this class is generated by {@code bench/scoreboard --render}
 * from the change-task results: per task, each kind of token's median without the code graph less its
 * median with it, summed over the tasks and divided by the graph calls the agent made in them with the
 * graph ({@code docs/user/web.md}). A cached step or a test class not re-run saves time, not tokens
 * the bench has measured, so it is credited none. No prices: the tokens are kept by model and priced
 * when shown ({@link TokensSaved#priced}). An agent the bench never ran is credited nothing and its
 * calls are counted as not measured, never at another agent's rates.
 *
 * @param measured the date of the newest bench run behind the rates, {@code yyyy-mm-dd}
 */
public record SavingsRates(String measured, Map<String, Agent> agents) {

    /**
     * One agent's rates.
     *
     * @param model the model the bench ran it on, which prices its tokens when jk read no other
     * @param cacheWrite1h whether it writes its prompt cache for an hour, a price of its own
     * @param question what one graph call in a code question saves
     * @param rename what one graph call in a rename saves
     */
    public record Agent(String model, boolean cacheWrite1h, TokensSaved.Counts question, TokensSaved.Counts rename) {}

    private static final String RESOURCE = "rates.json";

    private static volatile @Nullable SavingsRates shipped;

    public SavingsRates {
        agents = Collections.unmodifiableMap(new LinkedHashMap<>(agents));
    }

    /** The table this engine ships with. */
    public static SavingsRates shipped() {
        SavingsRates r = shipped;
        if (r == null) {
            try (InputStream in = SavingsRates.class.getResourceAsStream(RESOURCE)) {
                if (in == null) throw new IllegalStateException(RESOURCE + " is missing from the engine jar");
                r = parse(new String(in.readAllBytes(), StandardCharsets.UTF_8));
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
            shipped = r;
        }
        return r;
    }

    /** The table in {@code json}, the shape {@code bench/scoreboard.d/agents.py} writes. */
    static SavingsRates parse(String json) {
        Object root = MiniJson.parse(json);
        Map<String, Agent> agents = new LinkedHashMap<>();
        if (MiniJson.get(root, "agents") instanceof Map<?, ?> m) {
            for (Map.Entry<?, ?> e : m.entrySet()) {
                Object a = e.getValue();
                String model = MiniJson.str(a, "model");
                boolean hour = Boolean.TRUE.equals(MiniJson.get(a, "cacheWrite1h"));
                agents.put(
                        String.valueOf(e.getKey()),
                        new Agent(
                                model == null ? "" : model,
                                hour,
                                counts(MiniJson.get(a, "question"), hour),
                                counts(MiniJson.get(a, "rename"), hour)));
            }
        }
        return new SavingsRates(text(root, "measured"), agents);
    }

    /**
     * The agent whose rates credit a session whose client called itself {@code client}: the first
     * whose name the client's name holds, letters and digits alone compared ({@code codex-mcp-client}
     * is {@code codex}, {@code Claude Code} is {@code claude-code}), Antigravity's {@code agy}; null
     * for a client that names none, or names no client.
     */
    public @Nullable String agentOf(@Nullable String client) {
        if (client == null) return null;
        String c = letters(client);
        if (c.startsWith("antigravity") && agents.containsKey("agy")) return "agy";
        for (String name : agents.keySet()) if (c.contains(letters(name))) return name;
        return null;
    }

    private static String letters(String s) {
        return s.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]", "");
    }

    /**
     * What {@code action} saved a session whose client is {@code client}, on {@code model}, the model
     * jk read its agent ran on, or the one the bench ran it on when that is null; none for a failed
     * call or one of a kind the bench measures no tokens for. Null for a code answer or a refactoring
     * the bench has no rate for: an agent it never ran, or a kind of call it never measured for that
     * agent.
     */
    public @Nullable TokensSaved saved(ActionRecord action, @Nullable String client, @Nullable String model) {
        if (!ActionRecord.OK.equals(action.outcome())) return TokensSaved.NONE;
        TokensSaved.Counts perCall;
        if (ActionRecord.GRAPH.contains(action.kind())) perCall = rate(client, Agent::question);
        else if (ActionRecord.REFACTORINGS.contains(action.kind())) perCall = rate(client, Agent::rename);
        else return TokensSaved.NONE;
        if (perCall == null) return null;
        String agentModel = Objects.requireNonNull(agents.get(agentOf(client))).model();
        return TokensSaved.of(model == null || model.isBlank() ? agentModel : model, perCall);
    }

    /** {@code client}'s agent's rate of one kind, or null when the bench has none for it. */
    private TokensSaved.@Nullable Counts rate(@Nullable String client, Function<Agent, TokensSaved.Counts> kind) {
        String name = agentOf(client);
        Agent agent = name == null ? null : agents.get(name);
        if (agent == null) return null;
        TokensSaved.Counts c = kind.apply(agent);
        return c.equals(TokensSaved.Counts.ZERO) ? null : c;
    }

    /** One graph call's tokens by kind; its cache writes are 1-hour ones when {@code hour}. */
    private static TokensSaved.Counts counts(@Nullable Object tokens, boolean hour) {
        if (tokens == null) return TokensSaved.Counts.ZERO;
        long write = count(tokens, "cacheWrite");
        return new TokensSaved.Counts(
                count(tokens, "input"),
                count(tokens, "output"),
                count(tokens, "cacheRead"),
                hour ? 0 : write,
                hour ? write : 0);
    }

    private static long count(Object node, String key) {
        return MiniJson.get(node, key) instanceof Number n ? n.longValue() : 0;
    }

    private static String text(@Nullable Object node, String key) {
        String s = MiniJson.str(node, key);
        return s == null ? "" : s;
    }
}
