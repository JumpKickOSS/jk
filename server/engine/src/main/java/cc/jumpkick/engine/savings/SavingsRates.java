/**
 * The tokens one graph call saves an agent, as the bench measured them: one {@link Measurement} per
 * agent, model and effort level it ran, each with what a call saves in the question tasks and in the
 * rename tasks. {@code rates.json} beside this class is generated by {@code bench/scoreboard --render}
 * from the change-task results: per task, each kind of token's median without the code graph less its
 * median with it, summed over the tasks and divided by the graph calls the agent made in them with the
 * graph ({@code docs/user/web.md}); the same again per repository the tasks ran in, so a call is
 * credited the rate measured in the repository nearest its project's size. A cached step or a test
 * class not re-run saves time, not tokens the bench has measured, so it is credited none. No prices:
 * the tokens are kept by model and priced when shown ({@link TokensSaved#priced}).
 *
 * <p>The same file is published beside the price table in the signed update manifest, so a later bench
 * run reaches a running engine without a release: {@link #current} prefers the store's copy when it
 * was published after the one built in. Nothing credited is stored; the ledger prices the recorded
 * actions when it is read, so a newer table re-prices sessions recorded before it arrived.
 *
 * @param published when this table was published; a copy replaces another only when published after it
 * @param measured the date of the newest bench run behind the rates, {@code yyyy-mm-dd}
 * @param rates every measurement, in the file's order
 */
public record SavingsRates(Instant published, String measured, List<Measurement> rates) {

    /**
     * What the bench measured for one agent on one model at one effort level.
     *
     * @param agent the agent ({@code claude-code}, {@code codex}, …)
     * @param model the model id it ran on
     * @param effort the reasoning effort it ran at, or empty when the bench pinned none
     * @param measured the date of the newest run behind it, {@code yyyy-mm-dd}
     * @param cacheWrite1h whether it writes its prompt cache for an hour, a price of its own
     * @param question what one graph call in a code question saves
     * @param rename what one graph call in a rename saves
     */
    public record Measurement(
            String agent,
            String model,
            String effort,
            String measured,
            boolean cacheWrite1h,
            Rate question,
            Rate rename) {

        /** How machine output names it: {@code agent/model/effort/measured}. */
        public String id() {
            return agent + "/" + model + "/" + effort + "/" + measured;
        }
    }

    /**
     * What one graph call of one kind saves: over every task, and per repository size. Cache writes
     * are kept in {@link TokensSaved.Counts#cacheWrite}; the window they are priced at is decided when
     * a session is credited.
     *
     * @param all the rate over every task the bench ran both ways
     * @param sizes the rate in each repository, smallest first
     */
    public record Rate(TokensSaved.Counts all, List<Sized> sizes) {

        public static final Rate NONE = new Rate(TokensSaved.Counts.ZERO, List.of());

        public Rate {
            sizes = List.copyOf(sizes);
        }

        /** Whether the bench measured this kind at all. */
        boolean measured() {
            return !all.equals(TokensSaved.Counts.ZERO);
        }

        /**
         * The rate for a project of {@code lines} non-blank source lines: the one measured in the
         * repository nearest that size by ratio, or {@link #all} when the size is not known (0 or
         * less) or the bench measured none by size.
         */
        public TokensSaved.Counts at(long lines) {
            if (lines <= 0 || sizes.isEmpty()) return all;
            Sized nearest = sizes.getFirst();
            for (Sized s : sizes) {
                if (Math.abs(Math.log((double) s.lines() / lines))
                        < Math.abs(Math.log((double) nearest.lines() / lines))) nearest = s;
            }
            return nearest.counts();
        }
    }

    /**
     * The rate measured in one repository.
     *
     * @param lines the repository's non-blank lines of main and test sources ({@link ProjectLines})
     */
    public record Sized(long lines, TokensSaved.Counts counts) {}

    /**
     * Which measurements priced a call, and how closely they match its session.
     *
     * @param step 1 exact (agent, model and effort), 2 model and effort, 3 model, 4 agent, 5 best guess
     *     (every measurement)
     * @param measurements the {@link Measurement#id}s whose median priced it
     * @param unknown the session's fields JumpKick could not read ({@code agent}, {@code model}, {@code
     *     effort}), so the steps that need them were skipped
     */
    public record Match(int step, List<String> measurements, List<String> unknown) {

        public Match {
            measurements = List.copyOf(measurements);
            unknown = List.copyOf(unknown);
        }

        /** The step's name in machine output. */
        public String name() {
            return switch (step) {
                case 1 -> "exact";
                case 2 -> "model-effort";
                case 3 -> "model";
                case 4 -> "agent";
                default -> "best-guess";
            };
        }
    }

    /**
     * What a call saved, and the match that priced it.
     *
     * @param match null when the call saves no tokens the bench measures, or the table has no rate of
     *     its kind
     */
    public record Credit(TokensSaved tokens, @Nullable Match match) {
        public static final Credit NONE = new Credit(TokensSaved.NONE, null);
    }

    /** The file's name, built in beside this class and in the store as the copy the update check fetched. */
    public static final String FILE = "rates.json";

    private static final StoreFileMemo<SavingsRates> STORED = new StoreFileMemo<>(4, table -> 1);

    private static volatile @Nullable SavingsRates shipped;

    public SavingsRates {
        rates = List.copyOf(rates);
    }

    /** The table this engine ships with. */
    public static SavingsRates shipped() {
        SavingsRates r = shipped;
        if (r == null) {
            try (InputStream in = SavingsRates.class.getResourceAsStream(FILE)) {
                if (in == null) throw new IllegalStateException(FILE + " is missing from the engine jar");
                r = parse(new String(in.readAllBytes(), StandardCharsets.UTF_8));
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
            shipped = r;
        }
        return r;
    }

    /** The table in effect on this host: the store's copy when published after the built-in one. */
    public static SavingsRates current() {
        return current(storeFile());
    }

    /** As {@link #current()} with the store's copy at {@code file}. */
    public static SavingsRates current(Path file) {
        SavingsRates builtIn = shipped();
        try {
            return STORED.get(file, f -> parse(Files.readString(f, StandardCharsets.UTF_8)))
                    .filter(stored -> stored.published().isAfter(builtIn.published()))
                    .orElse(builtIn);
        } catch (IOException | RuntimeException e) {
            Log.debug("savings rates in the store are unreadable; the built-in ones apply", e);
            return builtIn;
        }
    }

    /** Where the engine keeps the newest table it fetched. */
    public static Path storeFile() {
        return JkDirs.store().resolve(FILE);
    }

    /**
     * The table in {@code json}, the shape {@code bench/scoreboard.d/agents.py} writes.
     *
     * @throws IllegalArgumentException when it is not JSON, has no {@code published} instant, or
     *     names no measurement
     */
    public static SavingsRates parse(String json) {
        Object root = MiniJson.parse(json);
        Instant published;
        try {
            published = Instant.parse(text(root, "published"));
        } catch (DateTimeParseException e) {
            throw new IllegalArgumentException("savings rates have no published instant", e);
        }
        List<Measurement> rates = new ArrayList<>();
        if (MiniJson.get(root, "rates") instanceof List<?> list) {
            for (Object m : list) {
                String agent = text(m, "agent");
                String model = text(m, "model");
                if (agent.isEmpty() || model.isEmpty()) continue;
                rates.add(new Measurement(
                        agent,
                        model,
                        text(m, "effort"),
                        text(m, "measured"),
                        Boolean.TRUE.equals(MiniJson.get(m, "cacheWrite1h")),
                        rate(MiniJson.get(m, "question")),
                        rate(MiniJson.get(m, "rename"))));
            }
        }
        if (rates.isEmpty()) throw new IllegalArgumentException("savings rates name no measurement");
        return new SavingsRates(published, text(root, "measured"), rates);
    }

    /**
     * The agent a session whose client called itself {@code client} is: the first measured agent whose
     * name the client's name holds, letters and digits alone compared ({@code codex-mcp-client} is
     * {@code codex}, {@code Claude Code} is {@code claude-code}), Antigravity's {@code agy}; else the
     * client's own name in that form, which matches no measurement; null for a session that named no
     * client.
     */
    public @Nullable String agentOf(@Nullable String client) {
        if (client == null || client.isBlank()) return null;
        String c = letters(client);
        Set<String> agents = agents();
        if (c.startsWith("antigravity") && agents.contains("agy")) return "agy";
        for (String name : agents) if (c.contains(letters(name))) return name;
        return c;
    }

    /** The agents measured, in the file's order. */
    public Set<String> agents() {
        Set<String> out = new LinkedHashSet<>();
        for (Measurement m : rates) out.add(m.agent());
        return out;
    }

    private static String letters(String s) {
        return s.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]", "");
    }

    private static final Pattern SUFFIX =
            Pattern.compile("(-\\d{8}|-\\d{4}-\\d{2}-\\d{2}|@\\d{8}|-latest|\\[[^]]*])+$");

    /**
     * {@code model} in the form ids of one model share, so a dated or suffixed id matches the
     * measured one: lowercased and trimmed; everything up to the last {@code /} dropped (a provider
     * prefix: {@code anthropic/claude-opus-5-5}); trailing dates ({@code -20261101}, {@code
     * -2026-11-01}, {@code @20261101}), {@code -latest} and bracketed suffixes ({@code [1m]}) dropped;
     * dots and underscores read as dashes ({@code claude-opus-5.5} is {@code claude-opus-5-5}). Empty
     * for no model.
     */
    static String normalized(@Nullable String model) {
        if (model == null) return "";
        String m = model.strip().toLowerCase(Locale.ROOT);
        m = m.substring(m.lastIndexOf('/') + 1);
        m = SUFFIX.matcher(m).replaceFirst("");
        return m.replace('.', '-').replace('_', '-');
    }

    /** The largest repository any rate was measured in, in lines; 0 when none was measured by size. */
    public long largest() {
        long max = 0;
        for (Measurement m : rates) {
            for (Sized s : m.question().sizes()) max = Math.max(max, s.lines());
            for (Sized s : m.rename().sizes()) max = Math.max(max, s.lines());
        }
        return max;
    }

    /**
     * What {@code action} saved a session whose client is {@code client}, on {@code model} (the model
     * jk read its agent ran on, or null), at {@code effort} (null: no agent's files say), in a project
     * of {@code lines} non-blank source lines, 0 when not known ({@link Rate#at}). {@link Credit#NONE}
     * for a failed call, one of a kind the bench measures no tokens for, or a kind no measurement has.
     *
     * <p>The rates are the closest measurement there is, in this order: (1) the same agent, model and
     * effort; (2) the same model and effort, any agent; (3) the same model, any agent or effort; (4)
     * the same agent, any model or effort; (5) every measurement. A step that needs a field the session
     * does not give is skipped; a step that matches several measurements takes their median. The tokens
     * are kept on {@code model}, or on the first matched measurement's model when it is not known, and
     * the cache writes are priced at the hour rate when the agent's own measurements say it writes for
     * an hour (else when the first matched one does).
     */
    public Credit saved(
            ActionRecord action, @Nullable String client, @Nullable String model, @Nullable String effort, long lines) {
        if (!ActionRecord.OK.equals(action.outcome())) return Credit.NONE;
        Function<Measurement, Rate> kind;
        if (ActionRecord.GRAPH.contains(action.kind())) kind = Measurement::question;
        else if (ActionRecord.REFACTORINGS.contains(action.kind())) kind = Measurement::rename;
        else return Credit.NONE;
        List<Measurement> having =
                rates.stream().filter(m -> kind.apply(m).measured()).toList();
        if (having.isEmpty()) return Credit.NONE;

        String agent = agentOf(client);
        String mod = normalized(model);
        String eff = effort == null ? "" : effort.strip().toLowerCase(Locale.ROOT);
        List<String> unknown = new ArrayList<>();
        if (agent == null) unknown.add("agent");
        if (mod.isEmpty()) unknown.add("model");
        if (eff.isEmpty()) unknown.add("effort");
        Predicate<Measurement> sameAgent = m -> m.agent().equals(agent);
        Predicate<Measurement> sameModel = m -> normalized(m.model()).equals(mod);
        Predicate<Measurement> sameEffort = m -> m.effort().equalsIgnoreCase(eff);

        int step = 5;
        List<Measurement> used = having;
        List<List<Measurement>> steps = new ArrayList<>();
        steps.add(
                agent != null && !mod.isEmpty() && !eff.isEmpty()
                        ? matching(having, sameAgent.and(sameModel).and(sameEffort))
                        : List.of());
        steps.add(!mod.isEmpty() && !eff.isEmpty() ? matching(having, sameModel.and(sameEffort)) : List.of());
        steps.add(!mod.isEmpty() ? matching(having, sameModel) : List.of());
        steps.add(agent != null ? matching(having, sameAgent) : List.of());
        for (int i = 0; i < steps.size(); i++) {
            if (!steps.get(i).isEmpty()) {
                step = i + 1;
                used = steps.get(i);
                break;
            }
        }

        List<TokensSaved.Counts> counts =
                used.stream().map(m -> kind.apply(m).at(lines)).toList();
        TokensSaved.Counts median = median(counts);
        List<Measurement> own = agent == null ? List.of() : matching(rates, sameAgent);
        boolean hour = (own.isEmpty() ? used.getFirst() : own.getFirst()).cacheWrite1h();
        if (hour) {
            median = new TokensSaved.Counts(
                    median.input(),
                    median.output(),
                    median.cacheRead(),
                    0,
                    median.cacheWrite() + median.cacheWrite1h());
        }
        String priceAs = model == null || model.isBlank() ? used.getFirst().model() : model;
        Match match = new Match(step, used.stream().map(Measurement::id).toList(), unknown);
        return new Credit(TokensSaved.of(priceAs, median), match);
    }

    private static List<Measurement> matching(List<Measurement> from, Predicate<Measurement> test) {
        return from.stream().filter(test).toList();
    }

    /** Each kind of token's median over {@code counts}; the mean of the middle two for an even number. */
    static TokensSaved.Counts median(Collection<TokensSaved.Counts> counts) {
        return new TokensSaved.Counts(
                median(counts, TokensSaved.Counts::input),
                median(counts, TokensSaved.Counts::output),
                median(counts, TokensSaved.Counts::cacheRead),
                median(counts, TokensSaved.Counts::cacheWrite),
                median(counts, TokensSaved.Counts::cacheWrite1h));
    }

    private static long median(Collection<TokensSaved.Counts> counts, ToLongFunction<TokensSaved.Counts> field) {
        long[] v = counts.stream().mapToLong(field).sorted().toArray();
        if (v.length == 0) return 0;
        int mid = v.length / 2;
        return v.length % 2 == 1 ? v[mid] : Math.round((v[mid - 1] + v[mid]) / 2.0);
    }

    /** One kind's rate: over every task, and per repository under {@code sizes}. */
    private static Rate rate(@Nullable Object node) {
        if (node == null) return Rate.NONE;
        List<Sized> sizes = new ArrayList<>();
        if (MiniJson.get(node, "sizes") instanceof List<?> list) {
            for (Object s : list) {
                long lines = count(s, "loc");
                if (lines > 0) sizes.add(new Sized(lines, counts(s)));
            }
        }
        return new Rate(counts(node), sizes);
    }

    /** One graph call's tokens by kind, its cache writes all under {@code cacheWrite}. */
    private static TokensSaved.Counts counts(@Nullable Object tokens) {
        if (tokens == null) return TokensSaved.Counts.ZERO;
        return new TokensSaved.Counts(
                count(tokens, "input"),
                count(tokens, "output"),
                count(tokens, "cacheRead"),
                count(tokens, "cacheWrite"),
                0);
    }

    private static long count(Object node, String key) {
        return MiniJson.get(node, key) instanceof Number n ? n.longValue() : 0;
    }

    private static String text(@Nullable Object node, String key) {
        String s = MiniJson.str(node, key);
        return s == null ? "" : s;
    }
}
