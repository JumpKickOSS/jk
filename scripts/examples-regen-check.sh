#!/usr/bin/env bash
# Regenerate each project of a jk-examples checkout the way a user would start it today and diff
# the manifest against the committed one: a scaffold-shaped example through `jk new` with the
# template it was started from, a converted one (05-recipes/migrate/*) through `jk import` of the
# build it carries. What the example adds, drops or sets differently is a finding unless its
# README names the key or its table (the example's documented deviations); identity, the example's
# own dependencies and the lock are the example's own and never compared. A scaffolded example's
# jk-guards.toml rule packs and its plugin manifest's sdk and jk-compat are compared with what jk new
# writes too.
#
# JumpKick's own pins are the template's, never the example's: every cc.jumpkick rule pack in a
# jk-guards.toml extends, cc.jumpkick coordinate in a jk.toml dependency table and plugin manifest
# sdk, in every example (workspace roots and members included), must name the generating jk's
# release, and one that does not is a finding no README excuses. JumpKick removes older releases
# from its repository, so such a pin resolves today and fails later.
#
# Usage: scripts/examples-regen-check.sh <jk-examples checkout> [--only <substring>]... [--out <dir>]
#   --only  only the examples whose path contains the substring (repeatable)
#   --out   where generated projects, logs and the report go (default target/examples-regen-check)
# Env: JK           the jk to run (default: jk on PATH)
#      JK_RELEASE   the release JumpKick's pins must name (default: the numeric version jk --version prints)
#
# The template an example was started from is read from the example: its framework table
# ([spring-boot], [quarkus], [micronaut], [helidon], [grails], [android]), a Ktor dependency, a
# library (no [application]) or an app, in the language of its sources; TEMPLATE_OF below names
# the ones the reading gets wrong (a value of "<id> <lang>" fixes the language too). A workspace root, a front end alone, a port and a benchmark are
# not one template's output and are reported as skipped, with the reason. A group root (a jk.toml
# with [workspaces] members, such as the checkout's own root) is no example either: it is skipped,
# and each project under it is an example of its own, not its member.
#
# Prints a Markdown report (also <out>/report.md): one row per example, then each finding. Exits 1
# when any example has an undocumented finding or fails to regenerate.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
JK="${JK:-jk}"
OUT="$ROOT/target/examples-regen-check"
EXAMPLES=""
ONLY=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --only) ONLY+=("$2"); shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    -h|--help) sed -n '2,30p' "$0"; exit 0 ;;
    -*) echo "unknown argument: $1" >&2; exit 2 ;;
    *) EXAMPLES="$(cd "$1" && pwd)" || exit 2; shift ;;
  esac
done
[[ -n "$EXAMPLES" ]] || { echo "usage: $0 <jk-examples checkout> [--only s]... [--out dir]" >&2; exit 2; }

# Examples whose template the reading below does not find: <path>=<template id>.
TEMPLATE_OF=(
  "01-start/java-cli=cli"
  "01-start/kotlin-cli=cli"
  "01-start/groovy-cli=app"
  "05-recipes/build-logic/line-count=app java"
  "05-recipes/plugins/jk-plugin/hello-plugin=plugin"
)

JK_RELEASE="${JK_RELEASE:-$("$JK" --version 2>/dev/null | head -1 | grep -oE '[0-9]+(\.[0-9]+)+' | head -1)}"
[[ -n "$JK_RELEASE" ]] || { echo "cannot read the release of $JK; set JK_RELEASE" >&2; exit 2; }

mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
REPORT="$OUT/report.md"
FINDINGS="$OUT/findings.md"
: >"$FINDINGS"
{
  echo "Examples regenerated by $("$JK" --version 2>/dev/null | head -1) from $(git -C "$EXAMPLES" rev-parse --short HEAD 2>/dev/null || echo "$EXAMPLES")"
  echo
  echo "| Example | Route | Result |"
  echo "|---|---|---|"
} >"$REPORT"
FAILED=0

wanted() {
  local path="$1" s
  [[ ${#ONLY[@]} -eq 0 ]] && return 0
  for s in "${ONLY[@]}"; do [[ "$path" == *"$s"* ]] && return 0; done
  return 1
}

# The template id and language an example was started from, as "<id> <lang>", or "skip <reason>".
template_of() {
  local dir="$1" rel="$2" entry lang="java" toml="$1/jk.toml"
  # The language of its sources, whatever the layout: Scala or Groovy beside Java is that template.
  if [[ -n "$(find "$dir" -path "$dir/target" -prune -o -name '*.scala' -print -quit)" ]]; then lang="scala"
  elif [[ -n "$(find "$dir" -path "$dir/target" -prune -o -name '*.groovy' -print -quit)" ]]; then lang="groovy"
  elif [[ -n "$(find "$dir" -path "$dir/target" -prune -o -name '*.kt' -print -quit)" ]]; then lang="kotlin"
  fi
  for entry in "${TEMPLATE_OF[@]}"; do
    [[ "${entry%%=*}" == "$rel" ]] && { [[ "${entry#*=}" == *" "* ]] && echo "${entry#*=}" || echo "${entry#*=} $lang"; return; }
  done
  if grep -qE '^\[workspace\]' "$toml"; then echo "skip a workspace root"; return; fi
  if grep -qE '^\[spring-boot\]' "$toml"; then echo "spring-boot/hello $lang"; return; fi
  if grep -qE '^\[quarkus\]' "$toml"; then echo "quarkus/hello $lang"; return; fi
  if grep -qE '^\[micronaut\]' "$toml"; then echo "micronaut/hello $lang"; return; fi
  if grep -qE '^\[helidon\]' "$toml"; then echo "helidon/quickstart java"; return; fi
  if grep -qE '^\[grails\]' "$toml"; then echo "grails/hello groovy"; return; fi
  if grep -qE '^\[android\]' "$toml"; then echo "android/compose kotlin"; return; fi
  if grep -qE 'io\.ktor:ktor-server' "$toml"; then echo "ktor-3 kotlin"; return; fi
  if [[ -f "$dir/package.json" ]] && ! grep -qE '^\[application\]|^main *=' "$toml"; then
    echo "skip a front end alone (jk new -f writes it through its generator)"; return
  fi
  if grep -qE '^\[application\]' "$toml"; then echo "app $lang"; else echo "library $lang"; fi
}

# The README text an example documents its deviations in: its own and its parents' up to the root.
readme_of() {
  local dir="$1"
  while [[ "$dir" == "$EXAMPLES"* ]]; do
    [[ -f "$dir/README.md" ]] && cat "$dir/README.md"
    [[ "$dir" == "$EXAMPLES" ]] && break
    dir="$(dirname "$dir")"
  done
}

# diff_manifests <label> <committed jk.toml> <generated jk.toml> <readme file>: one finding per
# line on stdout as "<kind>|<documented 0/1>|<label: ><text>"; nothing when they agree.
diff_manifests() {
  python3 -I - "$@" <<'PY'
import sys, tomllib, re

label, committed, generated, readme_path = sys.argv[1:5]
with open(committed, "rb") as f: a = tomllib.load(f)
with open(generated, "rb") as f: b = tomllib.load(f)
readme = open(readme_path, encoding="utf-8", errors="replace").read()

IDENTITY = {"name", "group", "version", "description"}
def own(path):
    head = path[0]
    if path == ("application", "main"): return True  # the example's own main class
    return (len(path) == 1 and head in IDENTITY) or head.endswith("dependencies") or head in ("libraries",)

def flatten(t, prefix=()):
    out = {}
    for k, v in t.items():
        p = prefix + (k,)
        if isinstance(v, dict):
            out.update(flatten(v, p) if v else {p + ("{}",): "table"})
        else:
            out[p] = v
    return out

def spell(path):
    if path[-1] == "{}": return "[" + ".".join(path[:-1]) + "]"
    if len(path) == 1: return path[0]
    return "[" + ".".join(path[:-1]) + "] " + path[-1]

def documented(path):
    keys = [k for k in path if k != "{}"]
    for i in range(1, len(keys) + 1):
        if "[" + ".".join(keys[:i]) + "]" in readme: return True
    return re.search(r"`" + re.escape(keys[-1]) + r"( =|`)", readme) is not None

def show(v):
    if v == "table": return "{}"
    if isinstance(v, str): return '"' + v + '"'
    if isinstance(v, bool): return "true" if v else "false"
    return str(v)

fa, fb = flatten(a), flatten(b)
for p in sorted(set(fa) | set(fb)):
    if own(p): continue
    if p not in fa:
        kind, text = "missing", f"{spell(p)}{'' if p[-1] == '{}' else ' = ' + show(fb[p])} (jk new writes it)"
    elif p not in fb:
        kind, text = "extra", f"{spell(p)}{'' if p[-1] == '{}' else ' = ' + show(fa[p])}"
    elif fa[p] != fb[p]:
        kind, text = "differs", f"{spell(p)}: {show(fa[p])}, jk new writes {show(fb[p])}"
    else:
        continue
    print(f"{kind}|{1 if documented(p) else 0}|{label + ': ' if label else ''}{text}")
PY
}

# diff_side_files <committed project> <generated project> <readme file>: the files beside jk.toml a
# template writes, in diff_manifests' line format: jk-guards.toml's [guards] extends rule packs, and
# the plugin manifest's [plugin] sdk and jk-compat. A pack's version that differs, and either plugin
# key, is never documented: they are the template's, set to the generating jk.
diff_side_files() {
  python3 -I - "$@" <<'PY'
import sys, tomllib, os

committed, generated, readme_path = sys.argv[1:4]
readme = open(readme_path, encoding="utf-8", errors="replace").read()

def load(path):
    if not os.path.isfile(path): return None
    with open(path, "rb") as f: return tomllib.load(f)

def packs(doc):
    out = {}
    ext = ((doc or {}).get("guards") or {}).get("extends") or []
    if isinstance(ext, str): ext = [ext]
    for gav in ext:
        parts = str(gav).split(":")
        if len(parts) == 3: out[parts[0] + ":" + parts[1]] = parts[2]
    return out

ca, cb = packs(load(os.path.join(committed, "jk-guards.toml"))), packs(load(os.path.join(generated, "jk-guards.toml")))
for ga in sorted(set(ca) | set(cb)):
    doc = 1 if ga in readme else 0
    if ga not in ca:
        print(f"missing|{doc}|jk-guards.toml: [guards] extends {ga}:{cb[ga]} (jk new writes it)")
    elif ga not in cb:
        print(f"extra|{doc}|jk-guards.toml: [guards] extends {ga}:{ca[ga]}")
    elif ca[ga] != cb[ga]:
        print(f"differs|0|jk-guards.toml: [guards] extends {ga}: {ca[ga]}, jk new writes {cb[ga]}")

manifest = os.path.join("src", "main", "resources", "jk-plugin.toml")
pa, pb = load(os.path.join(committed, manifest)), load(os.path.join(generated, manifest))
if pa is not None and pb is not None:
    for key in ("sdk", "jk-compat"):
        va, vb = (pa.get("plugin") or {}).get(key), (pb.get("plugin") or {}).get(key)
        if va != vb:
            print(f"differs|0|jk-plugin.toml: [plugin] {key}: {va!r}, jk new writes {vb!r}".replace("'", '"'))
PY
}

# stale_pins <examples checkout> <release> [<only>...]: one line per JumpKick pin in any example
# (whose path contains an <only> substring, when given) that does not name <release>, as
# "<file>: <what>"; nothing when every one does.
stale_pins() {
  python3 -I - "$@" <<'PY'
import sys, tomllib, os

root, release = sys.argv[1:3]
only = sys.argv[3:]
SKIP = {"target", "node_modules", ".git", "build"}

def jumpkick(group): return group == "cc.jumpkick" or group.startswith("cc.jumpkick.")

def dep_pins(doc):
    # every *dependencies table at any depth (variant overlays included), as (table, key, ga, version)
    def walk(t, path):
        for k, v in t.items():
            if isinstance(v, dict) and k.endswith("dependencies"):
                for key, spec in v.items():
                    ga = ver = None
                    if isinstance(spec, str) and spec.count(":") == 2:
                        g, a, ver = spec.split(":"); ga = g + ":" + a
                    elif isinstance(spec, dict) and isinstance(spec.get("version"), str) and spec.get("group"):
                        ga, ver = spec["group"] + ":" + spec.get("name", key), spec["version"]
                    if ga and jumpkick(ga.split(":")[0]): yield ".".join(path + [k]), key, ga, ver
            elif isinstance(v, dict):
                yield from walk(v, path + [k])
    yield from walk(doc, [])

for dirpath, dirnames, filenames in os.walk(root):
    dirnames[:] = sorted(d for d in dirnames if d not in SKIP)
    rel = os.path.relpath(dirpath, root)
    for name in sorted(filenames):
        path = os.path.join(dirpath, name)
        shown = os.path.normpath(os.path.join(rel, name))
        if name not in ("jk.toml", "jk-guards.toml", "jk-plugin.toml"): continue
        if only and not any(o in shown for o in only): continue
        try:
            with open(path, "rb") as f: doc = tomllib.load(f)
        except (OSError, tomllib.TOMLDecodeError):
            continue
        if name == "jk-guards.toml":
            ext = (doc.get("guards") or {}).get("extends") or []
            for gav in [ext] if isinstance(ext, str) else ext:
                parts = str(gav).split(":")
                if len(parts) == 3 and jumpkick(parts[0]) and parts[2] != release:
                    print(f"{shown}: [guards] extends {gav}, jk {release} writes {parts[0]}:{parts[1]}:{release}")
        elif name == "jk.toml":
            for table, key, ga, ver in dep_pins(doc):
                if ver != release:
                    print(f"{shown}: [{table}] {key} = {ga}:{ver}, jk {release} writes {ga}:{release}")
        elif name == "jk-plugin.toml":
            sdk = (doc.get("plugin") or {}).get("sdk")
            if isinstance(sdk, str) and sdk != release:
                print(f"{shown}: [plugin] sdk = \"{sdk}\", jk {release} writes \"{release}\"")
PY
}

# Record one example's findings; returns 1 when any is undocumented.
record() {
  local rel="$1" route="$2" lines="$3" undoc doc
  undoc="$(grep -c '|0|' <<<"$lines" || true)"
  doc="$(grep -c '|1|' <<<"$lines" || true)"
  [[ -z "$lines" ]] && { undoc=0; doc=0; }
  if [[ "$undoc" -eq 0 && "$doc" -eq 0 ]]; then
    echo "| \`$rel\` | $route | equal |" >>"$REPORT"
    return 0
  fi
  echo "| \`$rel\` | $route | $undoc undocumented, $doc documented |" >>"$REPORT"
  {
    echo
    echo "### \`$rel\` ($route)"
    echo
    while IFS='|' read -r kind is_doc text; do
      [[ -n "$kind" ]] || continue
      if [[ "$is_doc" == 1 ]]; then echo "- $kind (README names it): $text"; else echo "- **$kind**: $text"; fi
    done <<<"$lines"
  } >>"$FINDINGS"
  [[ "$undoc" -eq 0 ]]
}

regen_new() {
  local dir="$1" rel="$2" id="$3" lang="$4" work name group log lines
  work="$OUT/projects/${rel//\//__}"
  rm -rf "$work" && mkdir -p "$work"
  log="$OUT/logs/${rel//\//__}.log"
  mkdir -p "$OUT/logs"
  name="$(python3 -I -c 'import sys,tomllib; print(tomllib.load(open(sys.argv[1],"rb")).get("name",""))' "$dir/jk.toml")"
  group="$(python3 -I -c 'import sys,tomllib; print(tomllib.load(open(sys.argv[1],"rb")).get("group","com.example"))' "$dir/jk.toml")"
  [[ -n "$name" ]] || name="$(basename "$dir")"
  if ! (cd "$work" && JK_NONINTERACTIVE=1 CI=1 "$JK" new "$work/$name" -t "$id" -l "$lang" -W "$name" -U "$group" --no-module </dev/null >"$log" 2>&1); then
    echo "| \`$rel\` | jk new -t $id -l $lang | **failed to generate** (log: $log) |" >>"$REPORT"
    return 1
  fi
  readme_of "$dir" >"$work/README.txt"
  lines="$(diff_manifests "" "$dir/jk.toml" "$work/$name/jk.toml" "$work/README.txt"
    diff_side_files "$dir" "$work/$name" "$work/README.txt")"
  record "$rel" "jk new -t $id -l $lang" "$lines"
}

regen_import() {
  local dir="$1" rel="$2" build work log lines status=0 m
  if [[ -f "$dir/pom.xml" ]]; then build="pom.xml"
  elif [[ -f "$dir/settings.gradle.kts" ]]; then build="settings.gradle.kts"
  elif [[ -f "$dir/settings.gradle" ]]; then build="settings.gradle"
  else echo "| \`$rel\` | jk import | skipped: no build to import |" >>"$REPORT"; return 0; fi
  work="$OUT/projects/${rel//\//__}"
  log="$OUT/logs/${rel//\//__}.log"
  rm -rf "$work" && mkdir -p "$work" "$OUT/logs"
  rsync -a --exclude target --exclude build --exclude .gradle --exclude jk.toml --exclude jk-lock.toml \
    --exclude AGENTS.md --exclude CLAUDE.md "$dir/" "$work/"
  if ! (cd "$work" && JK_NONINTERACTIVE=1 CI=1 "$JK" -q import "$build" </dev/null >"$log" 2>&1); then
    echo "| \`$rel\` | jk import $build | **failed to import** (log: $log) |" >>"$REPORT"
    return 1
  fi
  readme_of "$dir" >"$work/README.txt"
  lines=""
  while IFS= read -r m; do
    local found
    if [[ ! -f "$work/$m" ]]; then
      found="extra|0|$m: jk import writes no such manifest"
    else
      found="$(diff_manifests "$m" "$dir/$m" "$work/$m" "$work/README.txt")"
    fi
    [[ -n "$found" ]] && lines+="$found"$'\n'
  done < <(cd "$dir" && find . -name jk.toml -not -path '*/target/*' -not -path '*/build/*' | sed 's#^\./##' | sort)
  record "$rel" "jk import $build" "${lines%$'\n'}" || status=1
  return "$status"
}

# Whether <dir>'s jk.toml groups self-contained workspaces ([workspaces] members): no example itself.
group_root() { grep -qE '^\[workspaces\]' "$1/jk.toml"; }

while IFS= read -r toml; do
  dir="$(dirname "$toml")"
  rel="${dir#"$EXAMPLES"/}"
  [[ "$dir" == "$EXAMPLES" ]] && rel="."
  case "$rel" in ports/*|bench/*) continue ;; esac
  # A member of a workspace is compared with its root, not on its own; a group root's are examples.
  parent="$(dirname "$dir")"
  member=0
  while [[ "$parent" == "$EXAMPLES"/* ]]; do
    if [[ -f "$parent/jk.toml" ]] && ! group_root "$parent"; then member=1; break; fi
    parent="$(dirname "$parent")"
  done
  [[ "$member" == 1 ]] && continue
  wanted "$rel" || continue
  if group_root "$dir"; then
    echo "| \`$rel\` | — | skipped: a group root ([workspaces]); each member is an example of its own |" >>"$REPORT"
    continue
  fi
  if [[ "$rel" == 05-recipes/migrate/* ]]; then
    regen_import "$dir" "$rel" || FAILED=1
    continue
  fi
  read -r id rest <<<"$(template_of "$dir" "$rel")"
  if [[ "$id" == skip ]]; then
    echo "| \`$rel\` | — | skipped: $rest |" >>"$REPORT"
    continue
  fi
  regen_new "$dir" "$rel" "$id" "$rest" || FAILED=1
done < <(find "$EXAMPLES" -name jk.toml -not -path '*/target/*' -not -path '*/node_modules/*' \
  -not -path '*/.git/*' -not -path '*/build/*' | sort)

if [[ -s "$FINDINGS" ]]; then
  { echo; echo "## Findings"; cat "$FINDINGS"; } >>"$REPORT"
fi

# JumpKick's own pins across every example, whichever route (or none) regenerates it.
STALE="$(stale_pins "$EXAMPLES" "$JK_RELEASE" ${ONLY[@]+"${ONLY[@]}"})"
if [[ -n "$STALE" ]]; then
  FAILED=1
  {
    echo
    echo "## JumpKick pins behind jk $JK_RELEASE"
    echo
    while IFS= read -r line; do echo "- **stale**: $line"; done <<<"$STALE"
  } >>"$REPORT"
else
  { echo; echo "Every JumpKick pin names jk $JK_RELEASE."; } >>"$REPORT"
fi
cat "$REPORT"
exit "$FAILED"
